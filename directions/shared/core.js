  function recommend(surface, hours, families) {
    var need = surface / Math.max(hours, 0.25);
    return G.products.filter(function (p) {
      return typeof p.key.productivity === 'number' && (!families || families.indexOf(p.family) > -1);
    }).map(function (p) { return { p: p, ratio: p.key.productivity / need, need: need }; })
      .sort(function (a, b) { return a.p.key.productivity - b.p.key.productivity; });
  }

